/* ============================================================
   投影幕和手機都要用到的規則常數

   為什麼要有這支檔案：手機上顯示的數字必須跟投影幕算的是同一個數。
   把換算的倍率抄兩份的話，改了一邊忘了另一邊，就會回到
   「手機上寫 30、投影幕上寫 3」那種兩邊講不同話的狀態。
   ============================================================ */

/**
 * 拔蘿蔔：拉幾下拔起一根。
 *
 * 10 下一根，這 10 下之間蘿蔔會從土裡慢慢冒出來 ——
 * 拉的當下就看得到進度，而不是拉滿才突然跳一個數字。
 * 投影幕拿它算分，手機拿它算「我拔了幾根」與那一根冒出多少。
 */
export const PER_CARROT = 10;

/**
 * 地理達人一題幾秒。
 *
 * 投影幕拿它計時，手機拿它自己倒數（秒數不從網路送 —— 每秒送一次
 * 乘以一百支手機是白燒的下行，而手機自己數一樣準）。
 * 兩邊抄成不同的值，畫面上就會出現「手機還有 3 秒、投影幕已經公布了」。
 */
export const GEO_ROUND_MS = 30_000;
