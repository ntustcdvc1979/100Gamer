/* ============================================================
   選邊站的題庫

   兩種題型，靠有沒有 answer 區分：

   answer 有填  → 有標準答案，答對得分。用來塞社團常識、校園冷知識。
   answer 沒填  → 沒有標準答案，「選的人最少」的那一區得分。
                  百人場的時候這個模式特別好玩：大家會互相猜別人會選什麼，
                  結果整場一起衝到同一區，然後全部沒分。

   四個選項各對應畫面的一個象限：
     0 左上　1 右上　2 左下　3 右下
   選項要短，手機上那一行也是靠它 —— 六個字以內最好。
   ============================================================ */

export interface Question {
  text: string;
  /** 四個選項，順序就是象限順序 */
  options: [string, string, string, string];
  /** 標準答案的索引。留空 = 少數派得分。 */
  answer?: number;
}

