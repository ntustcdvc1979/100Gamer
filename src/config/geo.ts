/* ============================================================
   地理達人的題庫

   每題是一個地點，玩家要在台灣地圖上點出位置，越近分數越高。

   照片：把圖檔放進 public/geo/（自己建這個資料夾），
   然後在 img 填檔名，例如 img: "geo/feiji.jpg"。
   Vite 會把 public/ 原封不動複製到網站根目錄。
   留空就只出文字，遊戲照樣跑得動 —— 但有照片好玩很多，
   尤其是「飛機巷」這種光看名字猜不到的。

   ⚠️ 照片會同時出現在投影幕和 100 支手機上，
   所以要壓過再放（長邊 800px、JPEG 0.7 以內），不然開場會很慢。

   經緯度可以用 Google 地圖右鍵「這是哪裡？」查。
   ============================================================ */

export interface GeoQuestion {
  /** 地點名稱 */
  name: string;
  /** 一句提示，可留空 */
  hint?: string;
  /** public/ 底下的路徑，例如 "geo/feiji.jpg"。留空就只出文字。 */
  img?: string;
  lon: number;
  lat: number;
}

